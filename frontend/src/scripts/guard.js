// ─────────────────────────────────────────────
// 로그인이 필요한 페이지(채팅 / 학습 기록 / 퀴즈 / 프로필)에 <script> 로 넣는다.
// 로그인하지 않았으면 로그인 페이지로 보낸다.
// ─────────────────────────────────────────────

import { requireLogin } from "./auth.js";

requireLogin();

// "뒤로 가기"로 돌아오면 브라우저가 이 페이지를 저장해 둔 그대로 되살릴 수 있다 (스크립트가 다시 안 돈다).
// 그 사이 로그아웃했으면 이전 사람의 화면이 그대로 보이므로, 되살아날 때 한 번 더 확인한다.
window.addEventListener("pageshow", (e) => {
  if (e.persisted) requireLogin();
});
